#!/usr/bin/env python3
# Generates src/core/timezone_posix.c: IANA id -> POSIX TZ rule, taken from
# the footer line of each TZif v2+ file (e.g. "EST5EDT,M3.2.0,M11.1.0").
# The R3 Pro firmware ships no zoneinfo tree, so the player sets TZ to the rule
# string itself. usage: gen_tz_posix.py [ZONEINFO_DIR] > src/core/timezone_posix.c
import re, sys, os
here = os.path.dirname(os.path.abspath(__file__))
zdir = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
src = open(os.path.join(here, "../../../src/core/timezone_data.c")).read()
ids = re.findall(r'\{ "([^"]+)", "', src)
print("/* Generated by boards/r3pro/tools/gen_tz_posix.py from tzdata footers; do not edit. */")
print('#include "timezone_posix.h"\n#include <string.h>\n')
print("static const struct { const char * id; const char * rule; } RULES[] = {")
# Legacy ids from the stock city list whose "backward" links may not be
# installed; the modern zone has the same current rules.
ALIASES = {
    "America/Indianapolis": "America/Indiana/Indianapolis", "America/Louisville": "America/Kentucky/Louisville",
    "America/Buenos_Aires": "America/Argentina/Buenos_Aires", "America/Catamarca": "America/Argentina/Catamarca",
    "America/Cordoba": "America/Argentina/Cordoba", "America/Jujuy": "America/Argentina/Jujuy",
    "America/Mendoza": "America/Argentina/Mendoza", "America/Godthab": "America/Nuuk",
    "Atlantic/Faeroe": "Atlantic/Faroe", "Africa/Asmera": "Africa/Nairobi", "Europe/Zaporozhye": "Europe/Kyiv",
    "Asia/Calcutta": "Asia/Kolkata", "Asia/Katmandu": "Asia/Kathmandu", "Asia/Choibalsan": "Asia/Ulaanbaatar",
    "Pacific/Truk": "Pacific/Port_Moresby", "Pacific/Ponape": "Pacific/Guadalcanal", "Pacific/Enderbury": "Pacific/Kanton",
}
missing = []
for i in ids:
    try:
        path = os.path.join(zdir, i)
        if not os.path.exists(path) and i in ALIASES: path = os.path.join(zdir, ALIASES[i])
        data = open(path, "rb").read()
        rule = data.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode()
        if not rule or "\0" in rule: raise ValueError
        print('    { "%s", "%s" },' % (i, rule.replace("\\", "\\\\").replace('"', '\\"')))
    except Exception:
        missing.append(i)
print("};\n")
print("const char * timezone_posix_rule(const char * iana_id) {")
print("    if (!iana_id) return NULL;")
print("    for (size_t i = 0; i < sizeof(RULES) / sizeof(RULES[0]); i++)")
print("        if (strcmp(RULES[i].id, iana_id) == 0) return RULES[i].rule;")
print("    return NULL;")
print("}")
if missing: sys.stderr.write("missing: %s\n" % " ".join(missing))
